using Npgsql;

var builder = WebApplication.CreateBuilder(args);
var connectionString = builder.Configuration.GetConnectionString("Default")
    ?? throw new InvalidOperationException("Connection string 'Default' is not configured.");
builder.Services.AddSingleton(NpgsqlDataSource.Create(connectionString));

var app = builder.Build();
var dataSource = app.Services.GetRequiredService<NpgsqlDataSource>();

// Each service creates only the table that it owns.
await using (var connection = await dataSource.OpenConnectionAsync())
await using (var command = new NpgsqlCommand("""
    CREATE TABLE IF NOT EXISTS users (
        id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        name TEXT NOT NULL,
        email TEXT NOT NULL UNIQUE,
        created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
    );
    """, connection))
{
    await command.ExecuteNonQueryAsync();
}

app.MapGet("/", () => Results.Ok(new { service = "user-service", status = "running" }));

app.MapGet("/health", async (NpgsqlDataSource db) =>
{
    try
    {
        await using var connection = await db.OpenConnectionAsync();
        await using var command = new NpgsqlCommand("SELECT 1", connection);
        await command.ExecuteScalarAsync();
        return Results.Ok(new { status = "healthy", database = "connected" });
    }
    catch
    {
        return Results.Json(new { status = "unhealthy", database = "unavailable" }, statusCode: 503);
    }
});

app.MapPost("/users", async (CreateUserRequest request, NpgsqlDataSource db) =>
{
    var name = request.Name?.Trim();
    var email = request.Email?.Trim().ToLowerInvariant();

    if (string.IsNullOrWhiteSpace(name) || string.IsNullOrWhiteSpace(email))
        return Results.BadRequest(new { error = "Поля name и email обязательны." });
    if (!email.Contains('@') || email.Length > 200)
        return Results.BadRequest(new { error = "Укажите корректный email (до 200 символов)." });

    try
    {
        await using var connection = await db.OpenConnectionAsync();
        await using var command = new NpgsqlCommand(
            "INSERT INTO users (name, email) VALUES (@name, @email) RETURNING id;", connection);
        command.Parameters.AddWithValue("name", name);
        command.Parameters.AddWithValue("email", email);
        var id = Convert.ToInt32(await command.ExecuteScalarAsync());
        return Results.Created($"/users/{id}", new UserResponse(id, name, email));
    }
    catch (PostgresException ex) when (ex.SqlState == PostgresErrorCodes.UniqueViolation)
    {
        return Results.Conflict(new { error = "Пользователь с таким email уже существует." });
    }
});

app.MapGet("/users", async (NpgsqlDataSource db) =>
{
    var users = new List<UserResponse>();
    await using var connection = await db.OpenConnectionAsync();
    await using var command = new NpgsqlCommand(
        "SELECT id, name, email FROM users ORDER BY id;", connection);
    await using var reader = await command.ExecuteReaderAsync();
    while (await reader.ReadAsync())
        users.Add(new UserResponse(reader.GetInt32(0), reader.GetString(1), reader.GetString(2)));
    return Results.Ok(users);
});

app.MapGet("/users/{id:int}", async (int id, NpgsqlDataSource db) =>
{
    await using var connection = await db.OpenConnectionAsync();
    await using var command = new NpgsqlCommand(
        "SELECT id, name, email FROM users WHERE id = @id;", connection);
    command.Parameters.AddWithValue("id", id);
    await using var reader = await command.ExecuteReaderAsync();
    if (!await reader.ReadAsync()) return Results.NotFound(new { error = "Пользователь не найден." });
    return Results.Ok(new UserResponse(reader.GetInt32(0), reader.GetString(1), reader.GetString(2)));
});

app.Run();

record CreateUserRequest(string? Name, string? Email);
record UserResponse(int Id, string Name, string Email);
