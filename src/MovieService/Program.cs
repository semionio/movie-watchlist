using Npgsql;

var builder = WebApplication.CreateBuilder(args);
var connectionString = builder.Configuration.GetConnectionString("Default")
    ?? throw new InvalidOperationException("Connection string 'Default' is not configured.");
builder.Services.AddSingleton(NpgsqlDataSource.Create(connectionString));

var app = builder.Build();
var dataSource = app.Services.GetRequiredService<NpgsqlDataSource>();

await using (var connection = await dataSource.OpenConnectionAsync())
await using (var command = new NpgsqlCommand("""
    CREATE TABLE IF NOT EXISTS movies (
        id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        title TEXT NOT NULL,
        release_year INTEGER NOT NULL CHECK (release_year BETWEEN 1888 AND 2100),
        genre TEXT NOT NULL,
        created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
    );
    """, connection))
{
    await command.ExecuteNonQueryAsync();
}

app.MapGet("/", () => Results.Ok(new { service = "movie-service", status = "running" }));

app.MapGet("/health", async (NpgsqlDataSource db) =>
{
    try
    {
        await using var connection = await db.OpenConnectionAsync();
        await using var command = new NpgsqlCommand("SELECT 1", connection);
        await command.ExecuteScalarAsync();
        return Results.Ok(new { status = "healthy", database = "connected" });
    }
    catch
    {
        return Results.Json(new { status = "unhealthy", database = "unavailable" }, statusCode: 503);
    }
});

app.MapPost("/movies", async (CreateMovieRequest request, NpgsqlDataSource db) =>
{
    var title = request.Title?.Trim();
    var genre = request.Genre?.Trim();
    if (string.IsNullOrWhiteSpace(title) || string.IsNullOrWhiteSpace(genre))
        return Results.BadRequest(new { error = "Поля title и genre обязательны." });
    if (request.Year < 1888 || request.Year > 2100)
        return Results.BadRequest(new { error = "Год должен быть в диапазоне от 1888 до 2100." });

    await using var connection = await db.OpenConnectionAsync();
    await using var command = new NpgsqlCommand("""
        INSERT INTO movies (title, release_year, genre)
        VALUES (@title, @year, @genre)
        RETURNING id;
        """, connection);
    command.Parameters.AddWithValue("title", title);
    command.Parameters.AddWithValue("year", request.Year);
    command.Parameters.AddWithValue("genre", genre);
    var id = Convert.ToInt32(await command.ExecuteScalarAsync());
    return Results.Created($"/movies/{id}", new MovieResponse(id, title, request.Year, genre));
});

app.MapGet("/movies", async (string? search, NpgsqlDataSource db) =>
{
    var movies = new List<MovieResponse>();
    await using var connection = await db.OpenConnectionAsync();
    var sql = string.IsNullOrWhiteSpace(search)
        ? "SELECT id, title, release_year, genre FROM movies ORDER BY id;"
        : "SELECT id, title, release_year, genre FROM movies WHERE title ILIKE @pattern OR genre ILIKE @pattern ORDER BY id;";
    await using var command = new NpgsqlCommand(sql, connection);
    if (!string.IsNullOrWhiteSpace(search))
        command.Parameters.AddWithValue("pattern", $"%{search.Trim()}%");
    await using var reader = await command.ExecuteReaderAsync();
    while (await reader.ReadAsync())
        movies.Add(new MovieResponse(reader.GetInt32(0), reader.GetString(1), reader.GetInt32(2), reader.GetString(3)));
    return Results.Ok(movies);
});

app.MapGet("/movies/{id:int}", async (int id, NpgsqlDataSource db) =>
{
    await using var connection = await db.OpenConnectionAsync();
    await using var command = new NpgsqlCommand(
        "SELECT id, title, release_year, genre FROM movies WHERE id = @id;", connection);
    command.Parameters.AddWithValue("id", id);
    await using var reader = await command.ExecuteReaderAsync();
    if (!await reader.ReadAsync()) return Results.NotFound(new { error = "Фильм не найден." });
    return Results.Ok(new MovieResponse(reader.GetInt32(0), reader.GetString(1), reader.GetInt32(2), reader.GetString(3)));
});

app.Run();

record CreateMovieRequest(string? Title, int Year, string? Genre);
record MovieResponse(int Id, string Title, int Year, string Genre);
