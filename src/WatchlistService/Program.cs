using System.Net;
using System.Net.Http.Json;
using Npgsql;

var builder = WebApplication.CreateBuilder(args);
var connectionString = builder.Configuration.GetConnectionString("Default")
    ?? throw new InvalidOperationException("Connection string 'Default' is not configured.");
var usersUrl = builder.Configuration["Services:Users"] ?? "http://user-service:8080";
var moviesUrl = builder.Configuration["Services:Movies"] ?? "http://movie-service:8080";

builder.Services.AddSingleton(NpgsqlDataSource.Create(connectionString));
builder.Services.AddHttpClient("users", client => client.BaseAddress = new Uri(usersUrl));
builder.Services.AddHttpClient("movies", client => client.BaseAddress = new Uri(moviesUrl));

var app = builder.Build();
var dataSource = app.Services.GetRequiredService<NpgsqlDataSource>();

await using (var connection = await dataSource.OpenConnectionAsync())
await using (var command = new NpgsqlCommand("""
    CREATE TABLE IF NOT EXISTS watchlist_items (
        id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        user_id INTEGER NOT NULL,
        movie_id INTEGER NOT NULL,
        movie_title TEXT NOT NULL,
        movie_year INTEGER NOT NULL,
        movie_genre TEXT NOT NULL,
        status TEXT NOT NULL CHECK (status IN ('planned', 'watching', 'watched', 'dropped')),
        notes TEXT NULL,
        created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
        CONSTRAINT uq_watchlist_user_movie UNIQUE (user_id, movie_id)
    );
    """, connection))
{
    await command.ExecuteNonQueryAsync();
}

app.MapGet("/", () => Results.Ok(new { service = "watchlist-service", status = "running" }));

app.MapGet("/health", async (NpgsqlDataSource db) =>
{
    try
    {
        await using var connection = await db.OpenConnectionAsync();
        await using var command = new NpgsqlCommand("SELECT 1", connection);
        await command.ExecuteScalarAsync();
        return Results.Ok(new { status = "healthy", database = "connected" });
    }
    catch
    {
        return Results.Json(new { status = "unhealthy", database = "unavailable" }, statusCode: 503);
    }
});

// This endpoint demonstrates service-to-service communication:
// it checks the user in User Service and the movie in Movie Service before saving.
app.MapPost("/watchlists/{userId:int}/items", async (
    int userId,
    CreateWatchlistItemRequest request,
    IHttpClientFactory httpClientFactory,
    NpgsqlDataSource db) =>
{
    if (userId <= 0 || request.MovieId <= 0)
        return Results.BadRequest(new { error = "userId и movieId должны быть положительными числами." });

    var status = request.Status?.Trim().ToLowerInvariant();
    var allowedStatuses = new[] { "planned", "watching", "watched", "dropped" };
    if (status is null || !allowedStatuses.Contains(status))
        return Results.BadRequest(new { error = "Допустимые статусы: planned, watching, watched, dropped." });

    try
    {
        var usersClient = httpClientFactory.CreateClient("users");
        using var userResponse = await usersClient.GetAsync($"/users/{userId}");
        if (userResponse.StatusCode == HttpStatusCode.NotFound)
            return Results.NotFound(new { error = "Нельзя добавить фильм: пользователь не найден в User Service." });
        if (!userResponse.IsSuccessStatusCode)
            return Results.Problem("User Service вернул ошибку.", statusCode: 503);

        var moviesClient = httpClientFactory.CreateClient("movies");
        using var movieResponse = await moviesClient.GetAsync($"/movies/{request.MovieId}");
        if (movieResponse.StatusCode == HttpStatusCode.NotFound)
            return Results.NotFound(new { error = "Нельзя добавить фильм: фильм не найден в Movie Service." });
        if (!movieResponse.IsSuccessStatusCode)
            return Results.Problem("Movie Service вернул ошибку.", statusCode: 503);

        var movie = await movieResponse.Content.ReadFromJsonAsync<MovieResponse>();
        if (movie is null)
            return Results.Problem("Movie Service вернул некорректный ответ.", statusCode: 502);

        await using var connection = await db.OpenConnectionAsync();
        await using var command = new NpgsqlCommand("""
            INSERT INTO watchlist_items
                (user_id, movie_id, movie_title, movie_year, movie_genre, status, notes)
            VALUES
                (@userId, @movieId, @title, @year, @genre, @status, @notes)
            RETURNING id;
            """, connection);
        command.Parameters.AddWithValue("userId", userId);
        command.Parameters.AddWithValue("movieId", movie.Id);
        command.Parameters.AddWithValue("title", movie.Title);
        command.Parameters.AddWithValue("year", movie.Year);
        command.Parameters.AddWithValue("genre", movie.Genre);
        command.Parameters.AddWithValue("status", status);
        command.Parameters.AddWithValue("notes", (object?)request.Notes?.Trim() ?? DBNull.Value);
        var id = Convert.ToInt32(await command.ExecuteScalarAsync());

        var result = new WatchlistItemResponse(id, userId, movie.Id, movie.Title, movie.Year, movie.Genre, status, request.Notes?.Trim());
        return Results.Created($"/watchlists/{userId}", result);
    }
    catch (PostgresException ex) when (ex.SqlState == PostgresErrorCodes.UniqueViolation)
    {
        return Results.Conflict(new { error = "Этот фильм уже есть в вотчлисте пользователя." });
    }
    catch (HttpRequestException)
    {
        return Results.Problem("Не удалось связаться с User Service или Movie Service. Проверьте, что оба сервиса запущены.", statusCode: 503);
    }
});

app.MapGet("/watchlists/{userId:int}", async (
    int userId,
    IHttpClientFactory httpClientFactory,
    NpgsqlDataSource db) =>
{
    try
    {
        var usersClient = httpClientFactory.CreateClient("users");
        using var userResponse = await usersClient.GetAsync($"/users/{userId}");
        if (userResponse.StatusCode == HttpStatusCode.NotFound)
            return Results.NotFound(new { error = "Пользователь не найден." });
        if (!userResponse.IsSuccessStatusCode)
            return Results.Problem("User Service вернул ошибку.", statusCode: 503);

        var items = new List<WatchlistItemResponse>();
        await using var connection = await db.OpenConnectionAsync();
        await using var command = new NpgsqlCommand("""
            SELECT id, user_id, movie_id, movie_title, movie_year, movie_genre, status, notes
            FROM watchlist_items
            WHERE user_id = @userId
            ORDER BY id;
            """, connection);
        command.Parameters.AddWithValue("userId", userId);
        await using var reader = await command.ExecuteReaderAsync();
        while (await reader.ReadAsync())
        {
            items.Add(new WatchlistItemResponse(
                reader.GetInt32(0), reader.GetInt32(1), reader.GetInt32(2),
                reader.GetString(3), reader.GetInt32(4), reader.GetString(5),
                reader.GetString(6), reader.IsDBNull(7) ? null : reader.GetString(7)));
        }
        return Results.Ok(new { userId, count = items.Count, items });
    }
    catch (HttpRequestException)
    {
        return Results.Problem("Не удалось связаться с User Service.", statusCode: 503);
    }
});

app.MapDelete("/watchlists/{userId:int}/items/{movieId:int}", async (
    int userId,
    int movieId,
    NpgsqlDataSource db) =>
{
    await using var connection = await db.OpenConnectionAsync();
    await using var command = new NpgsqlCommand(
        "DELETE FROM watchlist_items WHERE user_id = @userId AND movie_id = @movieId;", connection);
    command.Parameters.AddWithValue("userId", userId);
    command.Parameters.AddWithValue("movieId", movieId);
    var affected = await command.ExecuteNonQueryAsync();
    return affected == 0 ? Results.NotFound(new { error = "Запись не найдена." }) : Results.NoContent();
});

app.Run();

record CreateWatchlistItemRequest(int MovieId, string? Status, string? Notes);
record MovieResponse(int Id, string Title, int Year, string Genre);
record WatchlistItemResponse(int Id, int UserId, int MovieId, string MovieTitle, int MovieYear, string MovieGenre, string Status, string? Notes);
